function ReadProgress() {
  const bar = useRef(null);
  useOnScroll(() => {
    const el = bar.current, body = document.getElementById('article-body'); if (!el || !body) return;
    const r = body.getBoundingClientRect(), vh = window.innerHeight;
    el.style.transform = `scaleX(${clamp01((vh * 0.35 - r.top) / Math.max(1, r.height - vh * 0.5)).toFixed(4)})`;
  }, []);
  return <div aria-hidden="true" className="pointer-events-none fixed inset-x-0 top-[100px] z-[49] h-[2px] xl:top-[120px]"><div ref={bar} className="h-full origin-left bg-ndm-blue" style={{ transform: 'scaleX(0)' }} /></div>;
}

