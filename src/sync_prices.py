"""Copy the price list (src/pricing-data.jsx: PRICE_CATS) and the price helpers (src/price-lib.jsx) into both shells, between
the PRICES markers, so every page reads one source (round 29). Run after editing either file, then rebuild the pages.
usage: python3 src/sync_prices.py <NDM dir> <src dir>
"""
import re
import sys
from pathlib import Path

root, src = Path(sys.argv[1]), Path(sys.argv[2])
data = (src / 'pricing-data.jsx').read_text(encoding='utf-8')
a = data.index('const PRICE_CATS = [')
b = data.index('\n];\n', a) + 4
cats = data[a:b]
lhr = re.search(r'helper = "(.*?)\\n"\n', (src / 'build_pricing.py').read_text(encoding='utf-8')).group(1).split('\\n', 1)[1]
lib = (src / 'price-lib.jsx').read_text(encoding='utf-8')
block = '/* PRICES:BEGIN (generated by src/sync_prices.py from src/pricing-data.jsx and src/price-lib.jsx, do not edit here) */\n' + lhr + '\n' + cats + lib + '/* PRICES:END */\n'
for name in ['index.html', 'promotion.html']:
    f = root / name
    s = f.read_text(encoding='utf-8')
    if '/* PRICES:BEGIN' in s:
        i = s.index('/* PRICES:BEGIN'); j = s.index('/* PRICES:END */\n', i) + len('/* PRICES:END */\n')
        s = s[:i] + block + s[j:]
    else:
        m = re.search(r"\nconst slug = \(s\) => [^\n]*\n", s)
        s = s[:m.end()] + block + s[m.end():]
    f.write_text(s, encoding='utf-8')
    print('prices synced into', name)
